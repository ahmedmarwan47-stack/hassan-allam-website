// Generates src/data/blurPlaceholders.ts: a tiny (12px-wide) blurred preview
// of every JPG/PNG/WebP under public/images (except the transparent map cloud
// layers), keyed by its public path. The ProgressiveImage component paints it
// instantly while the real image loads.
//
// Run after adding or replacing images:  npm run blur
// Uses `sharp`, which ships with Next.js.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC = path.join(ROOT, "public");
const OUT = path.join(ROOT, "src/data/blurPlaceholders.ts");

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(jpe?g|png|webp)$/i.test(entry.name) && !/^cloud-|-cutout\./.test(entry.name)) yield full;
  }
}

const entries = [];
for await (const file of walk(path.join(PUBLIC, "images"))) {
  const buf = await sharp(file)
    .resize(12, null, { fit: "inside" })
    .flatten({ background: "#000000" })
    .jpeg({ quality: 60 })
    .toBuffer();
  const key = "/" + path.relative(PUBLIC, file).split(path.sep).join("/");
  entries.push([key, `data:image/jpeg;base64,${buf.toString("base64")}`]);
}
entries.sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: "${v}",`).join("\n");
await writeFile(
  OUT,
  `// Generated by scripts/gen-blur-placeholders.mjs — do not edit by hand.\n` +
    `// Run \`npm run blur\` after adding or replacing images in public/images.\n` +
    `export const BLUR_PLACEHOLDERS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`Wrote ${entries.length} placeholders to ${path.relative(ROOT, OUT)}`);
